export const getStoredTrendingDeals = () => {
  const deals = [];
  for (const product of STORED_PRODUCTS) {
    const listings = STORED_LISTINGS.filter(l => l.product_id === product.id);
    if (!listings.length) continue;

    const bestListing = listings.reduce((best, cur) => {
      const bestPrice = best.offer_price || best.price;
      const curPrice = cur.offer_price || cur.price;
      return curPrice < bestPrice ? cur : best;
    }, listings[0]);

    const original = bestListing.original_price || bestListing.price;
    const current = bestListing.offer_price || bestListing.price;
    const savings = Math.max(0, original - current);
    const discount_pct = original ? Math.round(((original - current) / original) * 1000) / 10 : 0;

    deals.push({
      id: product.id,
      canonical_name: product.canonical_name,
      brand: product.brand,
      category: product.category,
      price: current,
      original_price: original,
      savings,
      platform: bestListing.platform_name,
      rating: bestListing.rating,
      image_url: product.image_url,
      discount_pct,
      listing_id: bestListing.id
    });
  }

  deals.sort((a, b) => b.discount_pct - a.discount_pct);
  return deals;
};

